BEGIN;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE TABLE IF NOT EXISTS dw.dim_customer (
  customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL UNIQUE,
  full_name TEXT NOT NULL, city TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_product (
  product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL UNIQUE,
  sku TEXT NOT NULL, product_name TEXT NOT NULL, category_name TEXT NOT NULL,
  unit_cost NUMERIC(12,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_date (
  date_key INTEGER PRIMARY KEY,
  calendar_date DATE NOT NULL UNIQUE,
  calendar_year INTEGER NOT NULL,
  calendar_month INTEGER NOT NULL CHECK (calendar_month BETWEEN 1 AND 12),
  year_month TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_store (
  store_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id INTEGER NOT NULL UNIQUE,
  store_name TEXT NOT NULL, city TEXT NOT NULL, store_type TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_channel (
  channel_key SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS dw.fact_session_events (
  event_id TEXT PRIMARY KEY,
  customer_key BIGINT REFERENCES dw.dim_customer(customer_key),
  session_id TEXT NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL,
  date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
  channel_key SMALLINT NOT NULL REFERENCES dw.dim_channel(channel_key),
  event_type TEXT NOT NULL CHECK (event_type IN ('page_view','search','add_to_cart','checkout_start','purchase')),
  properties JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE IF NOT EXISTS dw.fact_sales (
  sale_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id INTEGER NOT NULL UNIQUE,
  order_id INTEGER NOT NULL,
  customer_key BIGINT NOT NULL REFERENCES dw.dim_customer(customer_key),
  product_key BIGINT NOT NULL REFERENCES dw.dim_product(product_key),
  date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
  store_key BIGINT NOT NULL REFERENCES dw.dim_store(store_key),
  channel_key SMALLINT NOT NULL REFERENCES dw.dim_channel(channel_key),
  quantity INTEGER NOT NULL,
  returned_quantity INTEGER NOT NULL,
  gross_amount NUMERIC(14,2) NOT NULL,
  discount_amount NUMERIC(14,2) NOT NULL,
  return_amount NUMERIC(14,2) NOT NULL,
  net_amount NUMERIC(14,2) NOT NULL,
  estimated_cost NUMERIC(14,2) NOT NULL,
  margin_amount NUMERIC(14,2) NOT NULL,
  CHECK (quantity > 0 AND returned_quantity BETWEEN 0 AND quantity)
);
INSERT INTO dw.dim_channel(channel_name) VALUES ('loja'),('ecommerce') ON CONFLICT DO NOTHING;
INSERT INTO dw.dim_customer(customer_id, full_name, city)
SELECT customer_id, full_name, city FROM customers
ON CONFLICT(customer_id) DO UPDATE SET full_name=EXCLUDED.full_name, city=EXCLUDED.city;
INSERT INTO dw.dim_product(product_id, sku, product_name, category_name, unit_cost)
SELECT p.product_id,p.sku,p.product_name,c.category_name,p.unit_cost FROM products p JOIN categories c USING(category_id)
ON CONFLICT(product_id) DO UPDATE SET sku=EXCLUDED.sku, product_name=EXCLUDED.product_name, category_name=EXCLUDED.category_name, unit_cost=EXCLUDED.unit_cost;
INSERT INTO dw.dim_store(store_id,store_name,city,store_type)
SELECT store_id,store_name,city,store_type FROM stores
ON CONFLICT(store_id) DO UPDATE SET store_name=EXCLUDED.store_name,city=EXCLUDED.city,store_type=EXCLUDED.store_type;
INSERT INTO dw.dim_date(date_key,calendar_date,calendar_year,calendar_month,year_month)
SELECT DISTINCT TO_CHAR(o.ordered_at::date,'YYYYMMDD')::INTEGER, o.ordered_at::date,
       EXTRACT(YEAR FROM o.ordered_at)::INTEGER, EXTRACT(MONTH FROM o.ordered_at)::INTEGER,
       TO_CHAR(o.ordered_at,'YYYY-MM') FROM orders o
ON CONFLICT(date_key) DO NOTHING;
INSERT INTO dw.fact_sales(order_item_id,order_id,customer_key,product_key,date_key,store_key,channel_key,
                          quantity,returned_quantity,gross_amount,discount_amount,return_amount,net_amount,estimated_cost,margin_amount)
SELECT i.order_item_id,o.order_id,dc.customer_key,dp.product_key,TO_CHAR(o.ordered_at::date,'YYYYMMDD')::INTEGER,
       ds.store_key,dch.channel_key,i.quantity,i.returned_quantity,
       i.quantity*i.unit_price,
       i.discount_amount,
       ROUND(i.returned_quantity*(i.unit_price-i.discount_amount/i.quantity),2),
       ROUND(i.quantity*i.unit_price-i.discount_amount-i.returned_quantity*(i.unit_price-i.discount_amount/i.quantity),2),
       (i.quantity-i.returned_quantity)*p.unit_cost,
       ROUND(i.quantity*i.unit_price-i.discount_amount-i.returned_quantity*(i.unit_price-i.discount_amount/i.quantity),2)
          -(i.quantity-i.returned_quantity)*p.unit_cost
FROM orders o JOIN order_items i USING(order_id)
JOIN customers c USING(customer_id) JOIN dw.dim_customer dc USING(customer_id)
JOIN products p USING(product_id) JOIN dw.dim_product dp USING(product_id)
JOIN stores s USING(store_id) JOIN dw.dim_store ds USING(store_id)
JOIN dw.dim_channel dch ON dch.channel_name=o.channel
WHERE o.status='completed'
ON CONFLICT(order_item_id) DO UPDATE SET
  order_id=EXCLUDED.order_id,customer_key=EXCLUDED.customer_key,product_key=EXCLUDED.product_key,
  date_key=EXCLUDED.date_key,store_key=EXCLUDED.store_key,channel_key=EXCLUDED.channel_key,
  quantity=EXCLUDED.quantity,returned_quantity=EXCLUDED.returned_quantity,gross_amount=EXCLUDED.gross_amount,
  discount_amount=EXCLUDED.discount_amount,return_amount=EXCLUDED.return_amount,net_amount=EXCLUDED.net_amount,
  estimated_cost=EXCLUDED.estimated_cost,margin_amount=EXCLUDED.margin_amount;
COMMIT;
