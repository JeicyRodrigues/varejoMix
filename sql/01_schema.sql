-- VarejoMix OLTP. Valores monetários em NUMERIC para evitar erro binário de ponto flutuante.
BEGIN;
CREATE TABLE IF NOT EXISTS categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name TEXT NOT NULL UNIQUE CHECK (length(trim(category_name)) > 0)
);
CREATE TABLE IF NOT EXISTS customers (
  customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
  email TEXT NOT NULL UNIQUE CHECK (position('@' in email) > 1),
  city TEXT NOT NULL,
  created_at DATE NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
  product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku TEXT NOT NULL UNIQUE,
  product_name TEXT NOT NULL,
  category_id INTEGER NOT NULL REFERENCES categories(category_id),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
  unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0 AND unit_cost <= unit_price)
);
CREATE TABLE IF NOT EXISTS stores (
  store_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_name TEXT NOT NULL UNIQUE,
  city TEXT NOT NULL,
  store_type TEXT NOT NULL CHECK (store_type IN ('physical','ecommerce'))
);
CREATE TABLE IF NOT EXISTS orders (
  order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
  store_id INTEGER NOT NULL REFERENCES stores(store_id),
  ordered_at TIMESTAMPTZ NOT NULL,
  channel TEXT NOT NULL CHECK (channel IN ('loja','ecommerce')),
  status TEXT NOT NULL CHECK (status IN ('completed','cancelled')),
  order_total NUMERIC(12,2) NOT NULL CHECK (order_total >= 0)
);
CREATE TABLE IF NOT EXISTS order_items (
  order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
  product_id INTEGER NOT NULL REFERENCES products(product_id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
  discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0 AND discount_amount <= quantity * unit_price),
  returned_quantity INTEGER NOT NULL DEFAULT 0 CHECK (returned_quantity >= 0 AND returned_quantity <= quantity),
  UNIQUE(order_id, product_id)
);
CREATE TABLE IF NOT EXISTS payments (
  payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL UNIQUE REFERENCES orders(order_id),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('card','pix','cash')),
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  payment_status TEXT NOT NULL CHECK (payment_status IN ('captured','void')),
  paid_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS inventory_movements (
  movement_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id INTEGER NOT NULL REFERENCES stores(store_id),
  product_id INTEGER NOT NULL REFERENCES products(product_id),
  moved_at TIMESTAMPTZ NOT NULL,
  movement_type TEXT NOT NULL CHECK (movement_type IN ('opening','sale','restock','adjustment')),
  quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0)
);
COMMIT;
